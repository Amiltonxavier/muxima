-- Account-level default role: `user.roleId` + the base `USER` role.
--
-- Root cause being fixed: sign-up created only the `user`/`account` rows and
-- every role in the system was event-scoped (`EventMember → Role`), so a new
-- user had no role at all until they created their first event. This
-- migration persists the account-level default for BOTH new and existing
-- users:
--
--   1. the base `USER` role row (idempotent — `role.name` is UNIQUE);
--   2. its grants, when the `permission` catalogue has been seeded;
--   3. the nullable `user.roleId` FK;
--   4. a back-fill assigning `USER` to every existing user, so no account is
--      left without a role.
--
-- The DDL for `user.roleId` is exactly what `prisma migrate` generated
-- (ADD COLUMN + FK, SET NULL on delete); the data statements are hand-written
-- because Prisma does not generate back-fills. `USER` grants NO administrative
-- capability — see the matrix in `packages/permissions/src/matrix.ts`.

-- ── 1. The base role ────────────────────────────────────────────────────────
INSERT INTO "role" ("id", "name", "description", "createdAt", "updatedAt")
VALUES (
    gen_random_uuid()::text,
    'USER',
    'Acesso base da conta: criar os próprios eventos e gerir o perfil. Dentro de um evento, os direitos vêm da membria.',
    CURRENT_TIMESTAMP,
    CURRENT_TIMESTAMP
)
ON CONFLICT ("name") DO NOTHING;

-- ── 2. Its grants (only when permissions exist — they come from the seed) ───
INSERT INTO "role_permission" ("id", "roleId", "permissionId")
SELECT gen_random_uuid()::text, r."id", p."id"
FROM "role" r
JOIN "permission" p
    ON p."key" IN (
        'events.create',
        'events.read',
        'activity.read',
        'profile.read',
        'profile.update',
        'profile.password.change',
        'notifications.read',
        'notifications.update',
        'notifications.delete'
    )
WHERE r."name" = 'USER'
ON CONFLICT ("roleId", "permissionId") DO NOTHING;

-- ── 3. `user.roleId` (schema diff, generated by prisma migrate) ─────────────
ALTER TABLE "user" ADD COLUMN "roleId" TEXT;

ALTER TABLE "user" ADD CONSTRAINT "user_roleId_fkey"
    FOREIGN KEY ("roleId") REFERENCES "role"("id")
    ON DELETE SET NULL ON UPDATE CASCADE;

-- ── 4. Back-fill: every existing user receives the default role ─────────────
UPDATE "user"
SET "roleId" = r."id"
FROM "role" AS r
WHERE r."name" = 'USER'
  AND "user"."roleId" IS NULL;
