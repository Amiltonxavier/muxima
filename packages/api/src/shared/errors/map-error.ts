import type { ZodIssue } from "zod";
import { ZodError } from "zod";
import {
	AppError,
	BadRequestError,
	ConflictError,
	ForbiddenError,
	InternalError,
	NotFoundError,
	RateLimitError,
	UnauthorizedError,
	ValidationError,
} from "./app-error";
import { ERROR_CODES } from "./codes";

/**
 * Friendly message for schema/database configuration drift (P2022).
 * Internal details (column names, SQL, paths) are only kept in server logs.
 */
const DATA_CONFIG_ERROR_MESSAGE =
	"Não foi possível carregar os dados devido a um problema de configuração. Tente novamente ou contacte o administrador.";

const NOT_FOUND_MESSAGE = "O registo solicitado não foi encontrado";
const CONFLICT_MESSAGE = "Já existe um registo com estes dados";
const INVALID_REFERENCE_MESSAGE = "Referência inválida a outro registo";

const BAD_REQUEST_MESSAGE =
	"Não foi possível processar o pedido. Verifique os dados enviados.";

const VALIDATION_MESSAGE = "Os dados enviados são inválidos.";

const METHOD_NOT_ALLOWED_MESSAGE = "Método não permitido.";
const PAYLOAD_TOO_LARGE_MESSAGE = "O ficheiro enviado é demasiado grande.";
const UNSUPPORTED_MEDIA_TYPE_MESSAGE =
	"O tipo de conteúdo enviado não é suportado.";

/**
 * Translates a single Zod issue into a user-facing PT-PT message.
 *
 * Message rules:
 * - `custom` issues keep the message defined in the schema (`.refine(..., { message })`
 *   and `.message(...)` calls are written in PT-PT across the codebase);
 * - every known generic issue code (invalid type, too small/big, invalid
 *   value/format, unknown keys, …) produces a fixed PT-PT message — the English
 *   defaults generated by Zod (`Invalid input: ...`, `Too small: ...`,
 *   `Invalid option: expected one of ...`) never reach the client.
 */
export function zodIssueToMessage(issue: ZodIssue, index: number): string {
	const originalMessage = issue.message ?? "";
	if (issue.code === "custom") {
		return originalMessage;
	}
	if (originalMessage.trim() && doesNotLookLikeZodDefault(originalMessage)) {
		return originalMessage;
	}
	// Zod reports a missing field as `invalid_type` (or `invalid_format` for
	// `z.email()`/`z.url()`-style schemas) with no input at all, which is what
	// distinguishes "campo obrigatório" from "valor com o tipo errado".
	if (
		issue.input === undefined &&
		(issue.code === "invalid_type" || issue.code === "invalid_format")
	) {
		return "Este campo é obrigatório.";
	}
	switch (issue.code) {
		case "invalid_type":
			return "Formato inválido.";
		case "invalid_value":
			// enum / literal / discriminated-union values
			return "Valor inválido.";
		case "invalid_union":
			return "Os dados enviados não correspondem a um formato válido.";
		case "too_small": {
			switch (issue.origin) {
				case "string":
				case "file":
					return "O valor é demasiado curto.";
				case "array":
				case "set":
					return "Selecione pelo menos o número mínimo de itens.";
				case "date":
					return "A data é demasiado antiga.";
				default:
					return "O valor é demasiado pequeno.";
			}
		}
		case "too_big": {
			switch (issue.origin) {
				case "string":
				case "file":
					return "O valor é demasiado longo.";
				case "array":
				case "set":
					return "Selecione no máximo o número permitido de itens.";
				case "date":
					return "A data é demasiado recente.";
				default:
					return "O valor é demasiado grande.";
			}
		}
		case "invalid_format":
			return formatToMessage(issue.format);
		case "unrecognized_keys":
			return "Campos não permitidos no objeto enviado.";
		case "not_multiple_of":
			return "O valor não respeita o intervalo permitido.";
		case "invalid_key":
			return "A chave do objeto é inválida.";
		case "invalid_element":
			return "Um dos elementos enviados é inválido.";
		default:
			return originalMessage.length > 0
				? originalMessage
				: `Valor inválido (campo ${index + 1}).`;
	}
}

/** Formats known `invalid_format` formats into PT-PT messages. */
function formatToMessage(format: string): string {
	switch (format) {
		case "uuid":
			return "O identificador não é válido.";
		case "email":
		case "hostname":
			return "O formato do email é inválido.";
		case "url":
		case "ipv4":
		case "ipv6":
		case "cidrv4":
		case "cidrv6":
			return "O URL não é válido.";
		case "ip":
		case "cidr":
			return "Endereço IP inválido.";
		case "date":
		case "time":
		case "datetime":
		case "duration":
			return "Formato de data inválido.";
		case "base64":
		case "base64url":
		case "hex":
			return "O conteúdo enviado não tem um formato válido.";
		case "jwt":
			return "O token enviado não é válido.";
		case "cuid":
		case "cuid2":
		case "ulid":
		case "ksuid":
		case "nanoid":
			return "O identificador não é válido.";
		case "regex":
		case "starts_with":
		case "ends_with":
		case "includes":
			return "Formato inválido.";
		default:
			return "Formato inválido.";
	}
}

const ZOD_DEFAULT_MARKERS: readonly string[] = [
	"Invalid input:",
	"Invalid option:",
	"Too small:",
	"Too big:",
	"Unrecognized key",
	"Expected ",
	"Invalid literal value",
	"Invalid UUID",
	"Invalid email",
	"Invalid URL",
	"Invalid date",
	"Invalid ISO",
	"Invalid base64",
	"Invalid number",
	"Invalid string",
	"must be",
];

/**
 * Heuristic: a message that does not match any of the English patterns Zod
 * generates by default is assumed to be a custom message (kept as-is — the
 * codebase writes custom schema messages in PT-PT).
 */
function doesNotLookLikeZodDefault(message: string): boolean {
	return !ZOD_DEFAULT_MARKERS.some((marker) => message.includes(marker));
}

/**
 * Builds the public `details.issues` array for validation errors.
 * Paths are joined with dots (`email`, `company.address`); an issue without a
 * path is reported as `*` (form-level error).
 */
export function zodIssuesToDetails(issues: ZodIssue[]): {
	issues: Array<{ path: string; message: string }>;
} {
	return {
		issues: issues.map((issue, index) => ({
			path: issue.path.length > 0 ? issue.path.join(".") : "*",
			message: zodIssueToMessage(issue, index),
		})),
	};
}

/**
 * Detect Prisma known-request errors by shape instead of `instanceof`:
 * the name/code pair is stable across Prisma runtimes (generated client,
 * bundled server build, test mocks) where `instanceof` can fail.
 */
export function isPrismaKnownRequestError(
	error: unknown,
): error is { code: string; message: string } {
	return (
		typeof error === "object" &&
		error !== null &&
		"code" in error &&
		typeof (error as { code: unknown }).code === "string" &&
		(error as { code: string }).code.startsWith("P") &&
		(error as { name?: unknown }).name === "PrismaClientKnownRequestError"
	);
}

/**
 * Central point of translation/classification for every error that did not
 * originate as an `AppError`.
 *
 * Supported origins, in order:
 * 1. `AppError` (any subclass) — passed through unchanged.
 * 2. `ZodError` → `422 VALIDATION_ERROR` with PT-PT `details.issues`.
 * 3. Fastify HTTP errors (rate limit, body parsing, media type, …) → same
 *    status, canonical public code, PT-PT message. The library message is
 *    never forwarded.
 * 4. Prisma known-request errors → `P2025` 404, `P2002` 409, `P2003` 400,
 *    `P2022` 500, any other `P*` 500. The Prisma code never leaks.
 * 5. Anything else (a plain `Error`) → `500 INTERNAL_SERVER_ERROR` with a
 *    generic message, because a plain `Error` carries no contract.
 *
 * Shared by REST (`error-handler.ts`) and oRPC (`packages/api/src/index.ts`),
 * so both surfaces expose the same `code`, `status` and PT-PT `message`.
 */
export function mapError(error: unknown): AppError {
	if (error instanceof AppError) return error;

	if (error instanceof ZodError) {
		const issues = error.issues;
		return new ValidationError(VALIDATION_MESSAGE, {
			details: zodIssuesToDetails(issues),
		});
	}

	// Fastify-level errors (rate limiting, body parsing, media type, …) keep
	// their HTTP status but get a stable public code and a PT-PT message. The
	// library message (often English) is never forwarded to the client.
	const fastifyStatus = (error as { statusCode?: unknown }).statusCode;
	if (
		typeof fastifyStatus === "number" &&
		fastifyStatus >= 400 &&
		fastifyStatus < 500
	) {
		switch (fastifyStatus) {
			case 429:
				return new RateLimitError();
			case 401:
				return new UnauthorizedError();
			case 403:
				return new ForbiddenError();
			case 404:
				return new NotFoundError();
			case 405:
				return new AppError(
					METHOD_NOT_ALLOWED_MESSAGE,
					405,
					ERROR_CODES.METHOD_NOT_ALLOWED,
				);
			case 413:
				return new AppError(
					PAYLOAD_TOO_LARGE_MESSAGE,
					413,
					ERROR_CODES.PAYLOAD_TOO_LARGE,
				);
			case 415:
				return new AppError(
					UNSUPPORTED_MEDIA_TYPE_MESSAGE,
					415,
					ERROR_CODES.UNSUPPORTED_MEDIA_TYPE,
				);
			case 422:
				return new ValidationError(VALIDATION_MESSAGE);
			default:
				return new BadRequestError(BAD_REQUEST_MESSAGE);
		}
	}

	if (isPrismaKnownRequestError(error)) {
		switch (error.code) {
			// Column referenced by the client does not exist in the database
			// (schema/migration drift) — never expose the column/table names.
			case "P2022":
				return new InternalError(DATA_CONFIG_ERROR_MESSAGE);
			// Record not found (e.g. update/delete of a removed row)
			case "P2025":
				return new NotFoundError(NOT_FOUND_MESSAGE);
			// Unique constraint violation
			case "P2002":
				return new ConflictError(CONFLICT_MESSAGE);
			// Foreign key constraint violation
			case "P2003":
				return new BadRequestError(INVALID_REFERENCE_MESSAGE);
			// Any other Prisma error (P1001 connection, P20xx schema, …) is an
			// infrastructure failure: never forwarded as-is.
			default:
				return new InternalError();
		}
	}

	return new InternalError();
}
